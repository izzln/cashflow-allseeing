// Bundle the built app (dist/) into the Worker as strings, so deploying needs no
// separate static-asset upload. Run after `vite build`.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const OUT = 'worker/static.generated.ts';
const DIST = 'dist';
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.txt': 'text/plain; charset=utf-8',
};

if (process.argv.includes('--if-missing') && existsSync(OUT)) process.exit(0);

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = {};
if (existsSync(DIST)) {
  for (const p of walk(DIST)) {
    const type = TYPES[extname(p)];
    if (!type) throw new Error(`Cannot embed ${p}: add its type to scripts/embed-assets.mjs`);
    const body = readFileSync(p, 'utf8');
    const etag = `"${createHash('sha256').update(body).digest('hex').slice(0, 16)}"`;
    files['/' + relative(DIST, p).split('\\').join('/')] = { type, etag, body };
  }
}
writeFileSync(
  OUT,
  `// Generated by scripts/embed-assets.mjs from dist/. Do not edit.\n` +
    `export const STATIC: Record<string, { type: string; etag: string; body: string }> = ${JSON.stringify(files)};\n`,
);
console.log(`Embedded ${Object.keys(files).length} file(s) into ${OUT}`);
